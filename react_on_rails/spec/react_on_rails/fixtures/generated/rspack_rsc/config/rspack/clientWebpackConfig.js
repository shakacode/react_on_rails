// The source code including full typescript support is available at:
// https://github.com/shakacode/react-on-rails-demo-ssr-hmr/blob/master/config/webpack/clientWebpackConfig.js

const commonWebpackConfig = require('./commonWebpackConfig');
const { config } = require('shakapacker');
const { resolve } = require('path');
const { RSCRspackPlugin } = require('react-on-rails-rsc/RspackPlugin');

const fallbackRscClientReferences = {
  directory: resolve(config.source_path),
  recursive: true,
  include: /\.(js|mjs|cjs|ts|mts|cts|jsx|tsx)$/,
};

// Resolves the RSC client-reference manifest produced by the discovery build. The
// manifest is a point-in-time snapshot regenerated by bin/shakapacker-precompile-hook,
// not on every webpack rebuild: a long-running `--watch` build reads it once at startup,
// so a new 'use client' file added mid-session is not picked up until the watch restarts
// (which re-runs the hook). Running bin/shakapacker directly after changing server
// components is covered by the best-effort staleness warning below.
//
// The resolution cascade below is mirrored, branch for branch, by the Pro dummy's
// hand-written rscManifestClientReferences.js and pinned on both sides by contract tests.
const rscClientReferences = (() => {
  // Required inside the IIFE rather than at the top of the file because the module-scope
  // bindings 'resolve' (from 'path') and 'config' (from 'shakapacker') are already
  // present — either pre-existing in the config or injected alongside this snippet by
  // the generator — so only extra helpers are pulled in here.
  const { existsSync, readFileSync, statSync } = require('fs');
  const { basename, isAbsolute, relative } = require('path');
  const configuredRefsJson = process.env.RSC_MANIFEST_CLIENT_REFERENCES_JSON;
  const configuredRegistrationEntry = process.env.REACT_ON_RAILS_RSC_REGISTRATION_ENTRY_PATH;
  const defaultRefsJson = resolve('ssr-generated/rsc-client-references.json');
  const defaultServerComponentRegistrationEntry = resolve(
    config.source_path,
    config.source_entry_path,
    '../generated/server-component-registration-entry.js',
  );
  const expectedServerComponentRegistrationEntry = 'server-component-registration-entry.js';
  const excludedRegistrationEntryPathComponents = [
    '.git',
    'log',
    'node_modules',
    'public',
    'spec',
    'test',
    'tmp',
    'vendor',
  ];
  const registrationEntryPathComponents = (entryPath) => {
    const rootRelativePath = relative(process.cwd(), entryPath);
    const scopedPath =
      rootRelativePath &&
      rootRelativePath !== '..' &&
      !rootRelativePath.startsWith('../') &&
      !rootRelativePath.startsWith('..\\') &&
      !isAbsolute(rootRelativePath)
        ? rootRelativePath
        : entryPath;

    return scopedPath.split(/[\\/]+/).filter(Boolean);
  };
  const validServerComponentRegistrationEntry = (entryPath) => {
    if (basename(entryPath) !== expectedServerComponentRegistrationEntry) return false;
    if (
      registrationEntryPathComponents(entryPath).some((component) =>
        excludedRegistrationEntryPathComponents.includes(component),
      )
    ) {
      return false;
    }

    try {
      return statSync(entryPath).isFile();
    } catch {
      return false;
    }
  };
  const serverComponentRegistrationEntry = (() => {
    if (configuredRegistrationEntry) {
      const configuredEntry = resolve(configuredRegistrationEntry);
      if (validServerComponentRegistrationEntry(configuredEntry)) return configuredEntry;
    }

    return defaultServerComponentRegistrationEntry;
  })();

  const readManifestReferences = (refsJson) => {
    let payload;
    try {
      payload = JSON.parse(readFileSync(refsJson, 'utf8'));
    } catch (err) {
      throw new Error(`Failed to parse RSC client references manifest ${refsJson}: ${err.message}`);
    }
    if (!Array.isArray(payload.refs)) {
      throw new Error(`Expected ${refsJson} to contain a refs array`);
    }

    return payload.refs;
  };

  const warnIfManifestStale = (refsJson) => {
    try {
      if (
        existsSync(serverComponentRegistrationEntry) &&
        statSync(serverComponentRegistrationEntry).mtimeMs > statSync(refsJson).mtimeMs
      ) {
        console.warn(
          `[react_on_rails] ${refsJson} is older than the server component ` +
            'registration entry; RSC client references may be stale. ' +
            'Re-run bin/shakapacker-precompile-hook.',
        );
      }
    } catch {
      // The manifest warning is non-fatal; the file can disappear between existsSync
      // and statSync while another build is rewriting ssr-generated.
    }
  };

  // These token checks are a compatibility gate, not a JavaScript parser. If either
  // generated file no longer has the discovery-build markers, fall back to the broad
  // scan with an upgrade warning instead of assuming the manifest will be produced.
  const fileContainsAll = (filePath, tokens) => {
    try {
      if (!existsSync(filePath)) return false;

      const content = readFileSync(filePath, 'utf8');
      return tokens.every((token) => content.includes(token));
    } catch {
      return false;
    }
  };

  const rscConfigSupportsDiscovery = () => {
    const rscWebpackConfig = resolve(__dirname, 'rscWebpackConfig.js');
    const precompileHook = resolve('bin/shakapacker-precompile-hook');

    return (
      fileContainsAll(rscWebpackConfig, ['RSC_REFERENCE_DISCOVERY_BUILD', 'RSCReferenceDiscoveryPlugin']) &&
      fileContainsAll(precompileHook, [
        'generate_rsc_manifest_client_references_if_needed',
        'RSC_REFERENCE_DISCOVERY_BUILD',
      ])
    );
  };

  if (configuredRefsJson) {
    const resolvedRefsJson = resolve(configuredRefsJson);
    if (!existsSync(resolvedRefsJson)) {
      throw new Error(
        `RSC_MANIFEST_CLIENT_REFERENCES_JSON is set but the file does not exist: ${resolvedRefsJson}`,
      );
    }
    warnIfManifestStale(resolvedRefsJson);
    return readManifestReferences(resolvedRefsJson);
  }

  if (process.env.RSC_REFERENCE_DISCOVERY_BUILD === 'true' || process.env.RSC_BUNDLE_ONLY === 'true') {
    return [fallbackRscClientReferences];
  }

  if (existsSync(defaultRefsJson)) {
    warnIfManifestStale(defaultRefsJson);
    return readManifestReferences(defaultRefsJson);
  }

  if (existsSync(serverComponentRegistrationEntry)) {
    if (!rscConfigSupportsDiscovery()) {
      console.warn(
        `[react_on_rails] Missing ${defaultRefsJson}, but this app's RSC webpack config ` +
          'or precompile hook does not support manifest discovery yet; falling back to broad client ' +
          'reference scan. Re-run rails g react_on_rails:rsc to update generated configs.',
      );
      return [fallbackRscClientReferences];
    }

    throw new Error(`Missing ${defaultRefsJson}. Run bin/shakapacker-precompile-hook before bin/shakapacker.`);
  }

  return [fallbackRscClientReferences];
})();

const configureClient = () => {
  const clientConfig = commonWebpackConfig();

  // server-bundle is special and should ONLY be built by the serverConfig
  // In case this entry is not deleted, a very strange "window" not found
  // error shows referring to window["webpackJsonp"]. That is because the
  // client config is going to try to load chunks.
  delete clientConfig.entry['server-bundle'];

  // Add React Server Components plugin for client bundle
  clientConfig.plugins.push(
    new RSCRspackPlugin({ isServer: false, clientReferences: rscClientReferences }),
  );

  return clientConfig;
};

module.exports = configureClient;
