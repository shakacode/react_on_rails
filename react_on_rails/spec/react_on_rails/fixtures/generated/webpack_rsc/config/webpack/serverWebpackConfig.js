// The source code including full typescript support is available at:
// https://github.com/shakacode/react-on-rails-demo-ssr-hmr/blob/master/config/webpack/serverWebpackConfig.js

const { config } = require('shakapacker');
const commonWebpackConfig = require('./commonWebpackConfig');

const bundler = config.assets_bundler === 'rspack'
  ? require('@rspack/core')
  : require('webpack');
const { resolve } = require('path');
const { RSCWebpackPlugin } = require('react-on-rails-rsc/WebpackPlugin');

const fallbackRscClientReferences = {
  directory: resolve(config.source_path),
  recursive: true,
  include: /\.(js|mjs|cjs|ts|mts|cts|jsx|tsx)$/,
};

// Resolves the RSC client-reference manifest produced by the discovery build. The
// manifest is a point-in-time snapshot regenerated by bin/shakapacker-precompile-hook,
// not on every webpack rebuild: a long-running `--watch` build reads it once at startup,
// so a new 'use client' file added mid-session is not picked up until the watch restarts
// (which re-runs the hook). Running bin/shakapacker directly after changing server
// components is covered by the best-effort staleness warning below.
//
// The resolution cascade below is mirrored, branch for branch, by the Pro dummy's
// hand-written rscManifestClientReferences.js and pinned on both sides by contract tests.
const rscClientReferences = (() => {
  // Required inside the IIFE rather than at the top of the file because the module-scope
  // bindings 'resolve' (from 'path') and 'config' (from 'shakapacker') are already
  // present — either pre-existing in the config or injected alongside this snippet by
  // the generator — so only extra helpers are pulled in here.
  const { existsSync, readFileSync, statSync } = require('fs');
  const { basename, isAbsolute, relative } = require('path');
  const configuredRefsJson = process.env.RSC_MANIFEST_CLIENT_REFERENCES_JSON;
  const configuredRegistrationEntry = process.env.REACT_ON_RAILS_RSC_REGISTRATION_ENTRY_PATH;
  const defaultRefsJson = resolve('ssr-generated/rsc-client-references.json');
  const defaultServerComponentRegistrationEntry = resolve(
    config.source_path,
    config.source_entry_path,
    '../generated/server-component-registration-entry.js',
  );
  const expectedServerComponentRegistrationEntry = 'server-component-registration-entry.js';
  const excludedRegistrationEntryPathComponents = [
    '.git',
    'log',
    'node_modules',
    'public',
    'spec',
    'test',
    'tmp',
    'vendor',
  ];
  const registrationEntryPathComponents = (entryPath) => {
    const rootRelativePath = relative(process.cwd(), entryPath);
    const scopedPath =
      rootRelativePath &&
      rootRelativePath !== '..' &&
      !rootRelativePath.startsWith('../') &&
      !rootRelativePath.startsWith('..\\') &&
      !isAbsolute(rootRelativePath)
        ? rootRelativePath
        : entryPath;

    return scopedPath.split(/[\\/]+/).filter(Boolean);
  };
  const validServerComponentRegistrationEntry = (entryPath) => {
    if (basename(entryPath) !== expectedServerComponentRegistrationEntry) return false;
    if (
      registrationEntryPathComponents(entryPath).some((component) =>
        excludedRegistrationEntryPathComponents.includes(component),
      )
    ) {
      return false;
    }

    try {
      return statSync(entryPath).isFile();
    } catch {
      return false;
    }
  };
  const serverComponentRegistrationEntry = (() => {
    if (configuredRegistrationEntry) {
      const configuredEntry = resolve(configuredRegistrationEntry);
      if (validServerComponentRegistrationEntry(configuredEntry)) return configuredEntry;
    }

    return defaultServerComponentRegistrationEntry;
  })();

  const readManifestReferences = (refsJson) => {
    let payload;
    try {
      payload = JSON.parse(readFileSync(refsJson, 'utf8'));
    } catch (err) {
      throw new Error(`Failed to parse RSC client references manifest ${refsJson}: ${err.message}`);
    }
    if (!Array.isArray(payload.refs)) {
      throw new Error(`Expected ${refsJson} to contain a refs array`);
    }

    return payload.refs;
  };

  const warnIfManifestStale = (refsJson) => {
    try {
      if (
        existsSync(serverComponentRegistrationEntry) &&
        statSync(serverComponentRegistrationEntry).mtimeMs > statSync(refsJson).mtimeMs
      ) {
        console.warn(
          `[react_on_rails] ${refsJson} is older than the server component ` +
            'registration entry; RSC client references may be stale. ' +
            'Re-run bin/shakapacker-precompile-hook.',
        );
      }
    } catch {
      // The manifest warning is non-fatal; the file can disappear between existsSync
      // and statSync while another build is rewriting ssr-generated.
    }
  };

  // These token checks are a compatibility gate, not a JavaScript parser. If either
  // generated file no longer has the discovery-build markers, fall back to the broad
  // scan with an upgrade warning instead of assuming the manifest will be produced.
  const fileContainsAll = (filePath, tokens) => {
    try {
      if (!existsSync(filePath)) return false;

      const content = readFileSync(filePath, 'utf8');
      return tokens.every((token) => content.includes(token));
    } catch {
      return false;
    }
  };

  const rscConfigSupportsDiscovery = () => {
    const rscWebpackConfig = resolve(__dirname, 'rscWebpackConfig.js');
    const precompileHook = resolve('bin/shakapacker-precompile-hook');

    return (
      fileContainsAll(rscWebpackConfig, ['RSC_REFERENCE_DISCOVERY_BUILD', 'RSCReferenceDiscoveryPlugin']) &&
      fileContainsAll(precompileHook, [
        'generate_rsc_manifest_client_references_if_needed',
        'RSC_REFERENCE_DISCOVERY_BUILD',
      ])
    );
  };

  if (configuredRefsJson) {
    const resolvedRefsJson = resolve(configuredRefsJson);
    if (!existsSync(resolvedRefsJson)) {
      throw new Error(
        `RSC_MANIFEST_CLIENT_REFERENCES_JSON is set but the file does not exist: ${resolvedRefsJson}`,
      );
    }
    warnIfManifestStale(resolvedRefsJson);
    return readManifestReferences(resolvedRefsJson);
  }

  if (process.env.RSC_REFERENCE_DISCOVERY_BUILD === 'true' || process.env.RSC_BUNDLE_ONLY === 'true') {
    return [fallbackRscClientReferences];
  }

  if (existsSync(defaultRefsJson)) {
    warnIfManifestStale(defaultRefsJson);
    return readManifestReferences(defaultRefsJson);
  }

  if (existsSync(serverComponentRegistrationEntry)) {
    if (!rscConfigSupportsDiscovery()) {
      console.warn(
        `[react_on_rails] Missing ${defaultRefsJson}, but this app's RSC webpack config ` +
          'or precompile hook does not support manifest discovery yet; falling back to broad client ' +
          'reference scan. Re-run rails g react_on_rails:rsc to update generated configs.',
      );
      return [fallbackRscClientReferences];
    }

    throw new Error(`Missing ${defaultRefsJson}. Run bin/shakapacker-precompile-hook before bin/shakapacker.`);
  }

  return [fallbackRscClientReferences];
})();

// Normalizes an entry of a webpack/rspack `rule.use` array to its loader path.
// Entries may be a bare string, a `{ loader, options }` object, or null.
function getLoaderPath(item) {
  if (typeof item === 'string') return item;
  if (item && typeof item.loader === 'string') return item.loader;
  return '';
}

function extractLoader(rule, loaderName) {
  if (!Array.isArray(rule.use)) return null;
  return rule.use.find((item) => getLoaderPath(item).includes(loaderName));
}

// rscBundle parameter: when true, skips RSCWebpackPlugin (RSC bundle doesn't need it)
const configureServer = (rscBundle = false) => {
  const serverWebpackConfig = commonWebpackConfig();

  // We just want the single server bundle entry
  const serverEntry = {
    'server-bundle': serverWebpackConfig.entry['server-bundle'],
  };

  if (!serverEntry['server-bundle']) {
    throw new Error(
      "Create a pack named 'server-bundle' containing all the server rendering files, for example 'server-bundle.js' or 'server-bundle.ts'",
    );
  }

  serverWebpackConfig.entry = serverEntry;

  // Remove the mini-css-extract-plugin from the style loaders because
  // the client build will handle exporting CSS.
  // replace file-loader with null-loader
  serverWebpackConfig.module.rules.forEach((loader) => {
    if (loader.use && loader.use.filter) {
      loader.use = loader.use.filter((item) => {
        const loaderPath = getLoaderPath(item);
        return !(
          loaderPath.includes('mini-css-extract-plugin') ||
          loaderPath.includes('cssExtractLoader') // Rspack uses this path
        );
      });
    }
  });

  // No splitting of chunks for a server bundle
  serverWebpackConfig.optimization = {
    minimize: false,
  };
  // Add RSC plugin for server bundle (handles client component references)
  // Skip for RSC bundle - it doesn't need RSCWebpackPlugin
  if (!rscBundle) {
    serverWebpackConfig.plugins.push(
      new RSCWebpackPlugin({ isServer: true, clientReferences: rscClientReferences }),
    );
  }
  serverWebpackConfig.plugins.unshift(new bundler.optimize.LimitChunkCountPlugin({ maxChunks: 1 }));

  // Custom output for the server-bundle
  // Using Shakapacker 9.0+ privateOutputPath for automatic sync with shakapacker.yml
  // This eliminates manual path configuration and keeps configs in sync.
  // Falls back to hardcoded path if private_output_path is not configured.
  const serverBundleOutputPath = config.privateOutputPath ||
    require('path').resolve(__dirname, '../../ssr-generated');

  serverWebpackConfig.output = {
    filename: 'server-bundle.js',
    globalObject: 'this',
    // Required for React on Rails Pro Node Renderer
    libraryTarget: 'commonjs2',
    path: serverBundleOutputPath,
    // No publicPath needed since server bundles are not served via web
    // https://webpack.js.org/configuration/output/#outputglobalobject
  };

  // Validate server bundle output path configuration
  // For Shakapacker 9.0+, verify privateOutputPath is configured in shakapacker.yml
  if (!config.privateOutputPath) {
    console.warn('⚠️  Shakapacker 9.0+ detected but private_output_path not configured in shakapacker.yml');
    console.warn('   Add to config/shakapacker.yml:');
    console.warn('     private_output_path: ssr-generated');
    console.warn('   Run: rails react_on_rails:doctor to validate your configuration');
  }


  // Don't hash the server bundle b/c would conflict with the client manifest
  // And no need for the MiniCssExtractPlugin
  serverWebpackConfig.plugins = serverWebpackConfig.plugins.filter(
    (plugin) =>
      plugin.constructor.name !== 'WebpackAssetsManifest' &&
      plugin.constructor.name !== 'MiniCssExtractPlugin' &&
      plugin.constructor.name !== 'ForkTsCheckerWebpackPlugin',
  );

  // Configure loader rules for SSR
  // Remove the mini-css-extract-plugin from the style loaders because
  // the client build will handle exporting CSS.
  // replace file-loader with null-loader
  const rules = serverWebpackConfig.module.rules;
  rules.forEach((rule) => {
    if (Array.isArray(rule.use)) {
      // remove the mini-css-extract-plugin and style-loader
      rule.use = rule.use.filter((item) => {
        const loaderPath = getLoaderPath(item);
        return !(
          loaderPath.includes('mini-css-extract-plugin') ||
          loaderPath.includes('cssExtractLoader') || // Rspack uses this path
          loaderPath === 'style-loader'
        );
      });
      const cssLoader = rule.use.find((item) => getLoaderPath(item).includes('css-loader'));
      if (cssLoader && cssLoader.options && cssLoader.options.modules) {
        cssLoader.options.modules = {
          ...(typeof cssLoader.options.modules === 'object' ? cssLoader.options.modules : {}),
          exportOnlyLocals: true,
        };
      }

      // Set SSR caller for Babel (if using Babel instead of SWC)
      const babelLoader = extractLoader(rule, 'babel-loader');
      if (babelLoader && babelLoader.options) {
        babelLoader.options.caller = { ssr: true };
      }

      // Skip writing image files during SSR by setting emitFile to false
    } else if (rule.use && (rule.use.loader === 'url-loader' || rule.use.loader === 'file-loader')) {
      rule.use.options.emitFile = false;
    }
  });

  // Avoid the webpack eval devtool, which triggers a webpack 5.106+ regression
  // with ESM default exports (ReferenceError: __WEBPACK_DEFAULT_EXPORT__ is not defined).
  // In development, cheap-module-source-map provides original line numbers in SSR error traces.
  // In production, devtool is disabled to avoid generating .map files.
  serverWebpackConfig.devtool = process.env.NODE_ENV === 'production' ? false : 'cheap-module-source-map';

  // React on Rails Pro uses Node renderer, so target must be 'node'
  // This fixes issues with libraries like Emotion and loadable-components
  serverWebpackConfig.target = 'node';

  // Disable Node.js polyfills - not needed when targeting Node
  serverWebpackConfig.node = false;

  // Source-mapped SSR stack traces in production:
  // The Pro Node renderer can remap bundled stack frames back to your original
  // source files (see docs/oss/building-features/node-renderer/debugging.md). This
  // needs source maps in the *production* server bundle, which the default above
  // disables (`devtool: false`). To opt in, replace only the `serverWebpackConfig.devtool`
  // assignment above (keep the eval-devtool note) with a production-aware variant so
  // development is unaffected. Both examples below use non-`eval` devtools, satisfying
  // that constraint. E.g.:
  //   serverWebpackConfig.devtool = process.env.NODE_ENV === 'production' ? 'source-map' : 'cheap-module-source-map';
  //     // 'source-map' — external .map (smaller bundle; stage the .map next to the uploaded bundle)
  //   serverWebpackConfig.devtool = process.env.NODE_ENV === 'production' ? 'inline-source-map' : 'cheap-module-source-map';
  //     // 'inline-source-map' — simplest; map travels inside the bundle (larger file)
  // The server bundle is never served to browsers; still, never expose
  // server-bundle source maps publicly.


  return serverWebpackConfig;
};

module.exports = {
  default: configureServer,
  extractLoader,
};
