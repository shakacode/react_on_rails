import { spawnSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { createApp } from '../src/create-app';
import { CliOptions } from '../src/types';
import { execCaptureArgs, execLiveArgs, getCommandVersion } from '../src/utils';

// These tests run createApp against a real temp directory with real git, so they check what the
// generated commits actually track. Only the slow or external steps are faked: rails new, bundle,
// and pnpm (execLiveArgs), plus the ruby call that renders Rails' git templates (execCaptureArgs).
jest.mock('../src/utils', () => ({
  ...jest.requireActual('../src/utils'),
  execLiveArgs: jest.fn(),
  execCaptureArgs: jest.fn(),
  getCommandVersion: jest.fn(),
  logStep: jest.fn(),
  logStepDone: jest.fn(),
  logError: jest.fn(),
  logSuccess: jest.fn(),
  logInfo: jest.fn(),
}));

const mockedExecLiveArgs = jest.mocked(execLiveArgs);
const mockedExecCaptureArgs = jest.mocked(execCaptureArgs);
const mockedGetCommandVersion = jest.mocked(getCommandVersion);

// railties 8.1.4 renders gitignore.tt to exactly this for create-react-on-rails-app. No Rails 7.x
// or 8.x template has a key-file rule: Rails appends one while it creates config/master.key, and
// only when .gitignore already exists, which rails new --skip-git prevents.
const RAILS_8_1_GITIGNORE = `# See https://help.github.com/articles/ignoring-files for more about ignoring files.
#
# Temporary files generated by your text editor or operating system
# belong in git's global ignore instead:
# \`$XDG_CONFIG_HOME/git/ignore\` or \`~/.config/git/ignore\`

# Ignore bundler config.
/.bundle

# Ignore all environment files.
/.env*

# Ignore all logfiles and tempfiles.
/log/*
/tmp/*
!/log/.keep
!/tmp/.keep

# Ignore pidfiles, but keep the directory.
/tmp/pids/*
!/tmp/pids/
!/tmp/pids/.keep

# Ignore storage (uploaded files in development and any SQLite databases).
/storage/*
!/storage/.keep
/tmp/storage/*
!/tmp/storage/
!/tmp/storage/.keep

/public/assets`;

const RAILS_8_1_GITATTRIBUTES = `# See https://git-scm.com/docs/gitattributes for more about git attribute files.

# Mark the database schema as having been generated.
db/schema.rb linguist-generated

# Mark any vendored files as having been vendored.
vendor/* linguist-vendored`;

const CREDENTIAL_KEY_FILE = /^config\/(credentials\/)?[^/]+\.key$/;

const baseOptions: CliOptions = {
  template: 'javascript',
  packageManager: 'npm',
  rspack: false,
  tailwind: false,
  pro: false,
  rsc: false,
  agentFiles: true,
};

let tmpRoot: string;
let gitEnv: NodeJS.ProcessEnv;

function git(args: string[], cwd?: string, env?: NodeJS.ProcessEnv): string {
  // createApp's commit env starts from process.env, so it is already isolated (see beforeEach).
  const result = spawnSync('git', args, { cwd, env: env ?? gitEnv, encoding: 'utf8' });
  if (result.status !== 0) {
    throw new Error(`git ${args.join(' ')} exited with ${String(result.status)}: ${result.stderr}`);
  }
  return result.stdout.trim();
}

function writeAppFile(appPath: string, relativePath: string, contents: string): void {
  const filePath = path.join(appPath, relativePath);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents);
}

// Stands in for rails new --skip-git: no .gitignore yet, plus the encrypted credentials files.
// Per-environment keys from `bin/rails credentials:edit --environment <env>` live in config/credentials/.
function fakeRailsNew(appPath: string): void {
  writeAppFile(appPath, 'Gemfile', 'source "https://rubygems.org"\n');
  writeAppFile(appPath, 'config/credentials.yml.enc', 'encrypted credentials placeholder\n');
  writeAppFile(appPath, 'config/master.key', 'test-only master key\n');
  writeAppFile(appPath, 'config/credentials/production.key', 'test-only production key\n');
}

function fakeExecLiveArgs(command: string, args: string[], cwd?: string, env?: NodeJS.ProcessEnv): void {
  if (command === 'git') {
    git(args, cwd, env);
  } else if (command === 'rails' && args[0] === 'new') {
    fakeRailsNew(path.join(tmpRoot, args[1]));
  } else if (command === 'bundle' && args[0] === 'add' && cwd) {
    fs.appendFileSync(path.join(cwd, 'Gemfile'), `gem "${args[1]}"\n`);
  } else if (command === 'bundle' && args.includes('react_on_rails:install') && cwd) {
    writeAppFile(cwd, 'package.json', '{\n  "name": "my-app"\n}\n');
  }
  // pnpm import/install leave nothing for these tests to fake.
}

function expectNoCredentialKeyFileInAnyCommit(appPath: string): void {
  const commits = git(['rev-list', '--reverse', 'HEAD'], appPath).split('\n');
  const firstCommitFiles = git(['ls-tree', '-r', '--name-only', commits[0]], appPath).split('\n');
  // Guards against a vacuous pass: the first commit must hold the app's credentials files.
  expect(firstCommitFiles).toEqual(expect.arrayContaining(['.gitignore', 'config/credentials.yml.enc']));

  commits.forEach((sha) => {
    const subject = git(['log', '-1', '--format=%s', sha], appPath);
    const keyFiles = git(['ls-tree', '-r', '--name-only', sha], appPath)
      .split('\n')
      .filter((file) => CREDENTIAL_KEY_FILE.test(file));
    expect({ subject, keyFiles }).toEqual({ subject, keyFiles: [] });
  });

  // The keys stay in place for the app to use; they are only kept out of git.
  expect(fs.readFileSync(path.join(appPath, 'config/master.key'), 'utf8')).toBe('test-only master key\n');
}

describe('createApp generated git history', () => {
  beforeEach(() => {
    tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'create-ror-app-history-'));
    // Drop inherited GIT_* variables (for example GIT_DIR inside a git hook) so every git call stays
    // in the temp app, and keep the developer's or runner's git config out of the generated commits.
    const inheritedEnv = Object.fromEntries(
      Object.entries(process.env).filter(([key]) => !key.startsWith('GIT_')),
    );
    gitEnv = {
      ...inheritedEnv,
      GIT_CONFIG_GLOBAL: path.join(tmpRoot, 'gitconfig'),
      GIT_CONFIG_NOSYSTEM: '1',
    };
    jest.replaceProperty(process, 'env', gitEnv);
    jest.spyOn(process, 'cwd').mockReturnValue(tmpRoot);
    jest.spyOn(process, 'exit').mockImplementation(((code?: number) => {
      throw new Error(`process.exit(${String(code)})`);
    }) as never);
    jest.spyOn(console, 'log').mockImplementation(() => {});
    jest.spyOn(console, 'error').mockImplementation(() => {});

    mockedExecLiveArgs.mockImplementation(fakeExecLiveArgs);
    mockedExecCaptureArgs.mockImplementation((command, args, cwd, env) => {
      if (command === 'ruby') {
        return args[2] === 'gitignore.tt' ? RAILS_8_1_GITIGNORE : RAILS_8_1_GITATTRIBUTES;
      }
      return git(args, cwd, env);
    });
    mockedGetCommandVersion.mockReturnValue('10.22.0');
  });

  afterEach(() => {
    jest.restoreAllMocks();
    fs.rmSync(tmpRoot, { recursive: true, force: true });
  });

  it.each<[string, Partial<CliOptions>]>([
    ['--standard with npm', {}],
    ['--pro with pnpm', { pro: true, packageManager: 'pnpm' }],
    ['--rsc with npm', { rsc: true }],
  ])('keeps credential key files out of every generated commit (%s)', (_label, overrides) => {
    createApp('my-app', { ...baseOptions, ...overrides });

    expectNoCredentialKeyFileInAnyCommit(path.join(tmpRoot, 'my-app'));
  });

  it('keeps credential key files out of every generated commit when Rails templates cannot be rendered', () => {
    mockedExecCaptureArgs.mockImplementation((command, args, cwd, env) => {
      if (command === 'ruby') {
        throw new Error('railties is not installed');
      }
      return git(args, cwd, env);
    });

    createApp('my-app', baseOptions);

    expectNoCredentialKeyFileInAnyCommit(path.join(tmpRoot, 'my-app'));
  });
});
